import type { PixelBuf } from '../../box/ground-art';
import { center, crop, render, tones } from './pen';
import type { Palette, Pen } from './pen';

/**
 * Ícones da mochila no estilo dos itens da 5ª geração: volume com quatro tons (luz de cima à esquerda), um brilho
 * branco, e contorno no tom escuro da própria cor (`sel`, aplicado no acabamento, por fora do desenho). Cabem num
 * quadro de 16×16 (14×14 de desenho mais o contorno).
 *
 * Paleta `Q(principal, segunda, terceira)`: a/b/c/d = brilho/luz/base/sombra da principal, e/f/g/h da segunda,
 * i/j/m/n da terceira; as maiúsculas são cores fixas (ver `FIX`).
 */

const FIX: Palette = {
  W: 0xffffff, V: 0xd4dae4, K: 0x383848, L: 0x98dc68, M: 0x50a848, N: 0x2f7036, T: 0xb07a48, U: 0x6a4628,
  Y: 0xffe878, Z: 0xd8a020, R: 0xe84848, P: 0xf8a0c0, B: 0x5890e8, O: 0xf09030,
};

export function Q(main: number, second = main, third = second, extra: Palette = {}): Palette {
  return { ...FIX, ...tones('abcd', main), ...tones('efgh', second), ...tones('ijmn', third), ...extra };
}

export interface Icon {
  rows: string;
  pal: Palette;
}

export const ic = (rows: string, pal: Palette): Icon => ({ rows, pal });

/** Ícone 16×16: o desenho centralizado e com contorno colorido. */
export function paintIcon(icon: Icon): PixelBuf {
  const art = crop(render((p: Pen) => p.map(1, 1, icon.rows, icon.pal), 18, 18, { shade: 'none', outline: 'sel' }));
  return center(art, 16, 16);
}

