/** Móveis de dentro de casa (os antigos, redesenhados) e as famílias que mudam de cor. */

const FABRIC: Record<string, number> = {
  vermelho: 0xd8463c, azul: 0x4f8fe0, verde: 0x4aa84a, rosa: 0xe86aa0, amarelo: 0xf2c84a, roxo: 0x8a5ad8, listrado: 0xe86aa0,
};
const STRIPES: Palette = { e: 0xffe27a, f: 0xe86aa0, g: 0x4f8fe0, h: 0x2f5fb8 };

/** Paleta de uma família: madeira + o tecido da cor (o listrado mistura três cores). */
export function fabric(color: string, wood = WOOD): Palette {
  const p = FP(wood, FABRIC[color] ?? 0x4f8fe0, 0xc8643c);
  return color === 'listrado' ? { ...p, ...STRIPES } : p;
}

