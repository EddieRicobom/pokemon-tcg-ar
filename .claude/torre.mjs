import { chromium } from 'playwright';
const out = process.argv[2];
const browser = await chromium.launch({ channel: 'msedge' });
const page = await browser.newPage({ viewport: { width: 390, height: 780 }, hasTouch: true, deviceScaleFactor: 2 });
page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.clock.setFixedTime(new Date('2026-10-17T12:00:00'));
await page.goto('http://localhost:5173/pokemon-tcg-ar/#/treinador');
await page.waitForTimeout(1200);
await page.evaluate(() => localStorage.setItem('tcg-ar-trainer-v1', JSON.stringify({ v: 1, xp: 9999999 })));
await page.goto('http://localhost:5173/pokemon-tcg-ar/?r=6#/vila');
await page.waitForTimeout(4000);
await page.goto('http://localhost:5173/pokemon-tcg-ar/?r=6#/treinador');
await page.waitForTimeout(1200);
await page.evaluate(() => {
  const k = 'tcg-ar-vila-v1';
  const v = JSON.parse(localStorage.getItem(k));
  v.digital = { ...v.digital, starterGiven: true, instances: [{ instanceId: 'dp_t0_25_0', originCardId: 'base1-58', dexId: 25, name: 'Pikachu', isDigitalPokemon: true, source: 'fonte', grantedAt: '2026-10-16T10:00:00.000Z', stage: 0 }] };
  localStorage.setItem(k, JSON.stringify(v));
});
await page.goto('http://localhost:5173/pokemon-tcg-ar/?r=7#/vila');
await page.waitForTimeout(6000);
for (let n = 0; n < 30; n++) {
  const b = page.locator('.speech-box button, .village-dialog button').first();
  if (!(await b.isVisible().catch(() => false))) break;
  await b.click();
  await page.waitForTimeout(350);
}
await page.screenshot({ path: `${out}-q.png` });
const walk = async (key, ms) => { await page.keyboard.down(key); await page.waitForTimeout(ms); await page.keyboard.up(key); await page.waitForTimeout(250); };
await walk('ArrowUp', 2950);
await walk('ArrowLeft', 5700);
await page.screenshot({ path: `${out}-0.png` });
await walk('ArrowUp', 120);
await page.getByRole('button', { name: /^A:/ }).click();
await page.waitForTimeout(800);
const enter = page.getByRole('button', { name: /Entrar na Torre/ });
if (await enter.isVisible().catch(() => false)) await enter.click(); else console.log('sem botão Entrar na Torre');
await page.waitForTimeout(3000);
await page.screenshot({ path: `${out}-1.png` });
const pick = page.locator('.survivor-pick button').first();
if (await pick.isVisible().catch(() => false)) await pick.click();
await page.waitForTimeout(3500);
await page.mouse.move(200, 500);
await page.mouse.down();
await page.mouse.move(260, 470, { steps: 6 });
await page.waitForTimeout(1200);
await page.screenshot({ path: `${out}-2.png` });
await page.mouse.up();
await browser.close();
